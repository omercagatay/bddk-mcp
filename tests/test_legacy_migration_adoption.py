@pytest.mark.postgres
@pytest.mark.asyncio
async def test_failure_after_normalization_rolls_back_every_metadata_change(pg_pool) -> None:
    connection, transaction = await _start_isolated_catalog(pg_pool)
    try:
        await _downgrade_catalog_to_supported_legacy(connection)

        from bddk_mcp.migrations.legacy import normalize_legacy_v1 as real_normalize

        async def normalize_then_fail(active_connection, inspection) -> None:
            await real_normalize(active_connection, inspection)
            raise asyncpg.PostgresError("deliberate private driver detail")

        with patch("bddk_mcp.migrations.runner.normalize_legacy_v1", new=normalize_then_fail):
            with pytest.raises(MigrationError, match="rolled back") as exc_info:
                await migrate(_PinnedPool(connection), adopt_legacy=True)  # type: ignore[arg-type]

        assert "deliberate private driver detail" not in str(exc_info.value)
        assert await connection.fetchval("SELECT pg_catalog.to_regclass('bddk_meta.schema_migrations')") is None
        assert await connection.fetchval(
            "SELECT attribute.attidentity = ''::pg_catalog.\"char\" "
            "FROM pg_catalog.pg_attribute AS attribute "
            "WHERE attribute.attrelid = 'public.document_chunks'::pg_catalog.regclass "
            "AND attribute.attname = 'id'"
        )
        assert await connection.fetchval(
            "SELECT pg_catalog.to_regclass('public.document_chunks_doc_id_chunk_index_key') IS NOT NULL"
        )
        assert await connection.fetchval(
            "SELECT function_record.proconfig IS NULL "
            "FROM pg_catalog.pg_proc AS function_record "
            "WHERE function_record.oid = "
            "'public.immutable_unaccent(pg_catalog.text)'::pg_catalog.regprocedure"
        )
    finally:
        await _finish_isolated_catalog(pg_pool, connection, transaction)


