@pytest.mark.postgres
@pytest.mark.asyncio
@pytest.mark.parametrize(
    "tamper",
    [
        "column",
        "function",
        "vector",
        "index",
        "trigger",
        "sequence",
        "constraint",
        "relation",
        "extra-relation",
        "table-acl",
        "sequence-acl",
        "rewrite-rule",
        "logical-publication",
        "owner",
    ],
)
async def test_adoption_refuses_tampered_or_incompatible_legacy_catalogs_without_partial_changes(
    pg_pool,
    tamper: str,
) -> None:
    connection, transaction = await _start_isolated_catalog(pg_pool)
    try:
        await _downgrade_catalog_to_supported_legacy(connection)
        if tamper == "column":
            await connection.execute("ALTER TABLE public.documents ADD COLUMN unmanaged pg_catalog.text")
        elif tamper == "function":
            await connection.execute(
                """
                CREATE OR REPLACE FUNCTION public.documents_tsv_trigger() RETURNS trigger AS $function$
                BEGIN
                    NEW.tsv := NULL;
                    RETURN NEW;
                END;
                $function$ LANGUAGE plpgsql
                """
            )
        elif tamper == "vector":
            await connection.execute(
                "ALTER TABLE public.document_chunks "
                "ALTER COLUMN embedding TYPE public.vector(384) "
                "USING NULL::public.vector(384)"
            )
        elif tamper == "index":
            await connection.execute("DROP INDEX public.idx_documents_tsv")
        elif tamper == "trigger":
            await connection.execute("ALTER TABLE public.documents DISABLE TRIGGER trg_documents_tsv")
        elif tamper == "sequence":
            await connection.execute("ALTER SEQUENCE public.document_chunks_id_seq CACHE 2")
        elif tamper == "constraint":
            await connection.execute("ALTER TABLE public.sync_metadata DROP CONSTRAINT sync_metadata_pkey")
        elif tamper == "relation":
            await connection.execute("ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY")
        elif tamper == "extra-relation":
            await connection.execute("CREATE TABLE public.unmanaged_relation (id pg_catalog.int4)")
        elif tamper == "table-acl":
            await connection.execute("GRANT SELECT ON public.documents TO PUBLIC")
        elif tamper == "sequence-acl":
            await connection.execute("GRANT USAGE ON SEQUENCE public.document_chunks_id_seq TO PUBLIC")
        elif tamper == "rewrite-rule":
            await connection.execute(
                "CREATE RULE unmanaged_documents_update AS ON UPDATE TO public.documents DO ALSO NOTHING"
            )
        elif tamper == "logical-publication":
            await connection.execute("CREATE PUBLICATION unmanaged_publication FOR TABLE public.documents")
        else:
            await connection.execute("RESET ROLE")
            await connection.execute("CREATE ROLE incompatible_legacy_owner")
            await connection.execute("ALTER TABLE public.documents OWNER TO incompatible_legacy_owner")
            await connection.execute("SET LOCAL ROLE bddk_test_schema_owner")

        with pytest.raises(LegacyAdoptionError, match="No corpus rows were changed"):
            await migrate(_PinnedPool(connection), adopt_legacy=True)  # type: ignore[arg-type]

        assert await connection.fetchval("SELECT pg_catalog.to_regclass('bddk_meta.schema_migrations')") is None
        assert await connection.fetchval("SELECT pg_catalog.to_regclass('bddk_operator.operator_jobs')") is None
        assert await connection.fetchval(
            "SELECT attribute.attidentity = ''::pg_catalog.\"char\" "
            "FROM pg_catalog.pg_attribute AS attribute "
            "WHERE attribute.attrelid = 'public.document_chunks'::pg_catalog.regclass "
            "AND attribute.attname = 'id'"
        )
    finally:
        await _finish_isolated_catalog(pg_pool, connection, transaction)


